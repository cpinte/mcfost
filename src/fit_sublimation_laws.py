#!/usr/bin/env python3
"""
Sublimation laws of the MCFOST dust files (.sub files)

Generates the .sub files read by MCFOST next to the optical indices files of
utils/Dust, and copies of the optical indices files with a constant sublimation
temperature consistent with the law (used with -constant_sublimation_temperature
and for the optically thin sublimation radius).

Law : T_sub = T0 (rho_gas / rho0)^gamma, rho_gas = total gas density [g/cm3]

Sources
- Isella & Natta 2005, A&A 438, 899, Eq. 16 : silicates, T0 = 2000 K, gamma = 1.95e-2
  (published power law, a fit to the olivine values of Pollack et al. 1994)
- Pollack et al. 1994, ApJ 421, 615, Table 3 : vaporisation temperatures at 8 gas
  densities for a solar-composition gas. The power laws of pyroxene, iron and water
  ice are least-squares fits of log T vs log rho to these values (this script).

The Pollack et al. temperatures are for the total gas density and assume solar
abundances (e.g. water ice: 52% of the oxygen in ice, disk case, footnote d).

Usage
  python3 fit_sublimation_laws.py                      # print the fits
  python3 fit_sublimation_laws.py -o sub_files         # also write the files
  python3 fit_sublimation_laws.py -o sub_files --dust_dir $MCFOST_UTILS/Dust
"""

import argparse
import os
import numpy as np

# Pollack et al. 1994, Table 3 : vaporisation temperatures [K]
P94_rho = 10.0 ** np.arange(-18, -3, 2)  # gas density [g/cm3] : 1e-18 ... 1e-4
P94_T = {
    "olivine":        [929, 997, 1076, 1168, 1277, 1408, 1570, 1774],
    "orthopyroxene":  [920, 980, 1049, 1129, 1222, 1331, 1462, 1621],
    "iron":           [835, 908, 994, 1100, 1230, 1395, 1612, 1908],
    "water ice disk": [109, 118, 129, 143, 159, 180, 207, 244],  # footnote d
    "water ice cloud": [106, 115, 125, 138, 153, 172, 197, 230],  # footnote c
}
P94_ref = "Pollack et al. 1994, ApJ 421, 615, Table 3"

# Laws : either published (T0, rho0, gamma) or fitted to a Pollack et al. species
laws = {
    "silicate": dict(T0=2000.0, rho0=1.0, gamma=0.0195,
                     reference="Isella & Natta 2005, A&A 438, 899, Eq. 16",
                     compare="olivine"),
    "pyroxene": dict(fit="orthopyroxene"),
    "iron": dict(fit="iron"),
    "water ice": dict(fit="water ice disk"),
}

# Optical indices files of utils/Dust and their law. Not included : composites
# (MW89, grain_comp*), opacity files (Pascucci_optSi, PAH*), carbon, corundum and
# CO2 ice (no verified density-dependent law).
dust_files = {
    "Draine_Si.dat": "silicate",
    "Draine_Si_sUV.dat": "silicate",
    "dlsi_opct.dat": "silicate",
    "lgsi_opct.dat": "silicate",
    "crstsi_opct.dat": "silicate",
    "Olivine.dat": "silicate",
    "Olivine_modif.dat": "silicate",
    "Olivine_no_SI.dat": "silicate",
    "indices_mc3d.dat": "silicate",
    "indices_mc3d_sil.dat": "silicate",
    "nk2_Mg07Fe03SiO3.dat": "pyroxene",
    "Fe-Posch.dat": "iron",
    "ice_opct.dat": "water ice",
    "waterice210K.dat": "water ice",
    "porousice_james.dat": "water ice",
}


def fit_power_law(rho, T, rho_min=0.0, rho_max=np.inf):
    """Least-squares fit of log10 T = log10 T0 + gamma log10 rho (rho0 = 1 g/cm3)."""
    sel = (rho >= rho_min) & (rho <= rho_max)
    gamma, log_T0 = np.polyfit(np.log10(rho[sel]), np.log10(np.asarray(T, float)[sel]), 1)
    return 10.0 ** log_T0, gamma


def power_law(rho, T0, rho0, gamma):
    return T0 * (rho / rho0) ** gamma


def max_relative_error(T0, rho0, gamma, species):
    T = np.asarray(P94_T[species], float)
    return np.max(np.abs(power_law(P94_rho, T0, rho0, gamma) / T - 1.0))


def get_laws(rho_min, rho_max):
    out = {}
    for name, law in laws.items():
        law = dict(law)
        if "fit" in law:
            species = law["fit"]
            law["T0"], law["gamma"] = fit_power_law(P94_rho, P94_T[species], rho_min, rho_max)
            law["rho0"] = 1.0
            law["reference"] = P94_ref + ", " + species + " (power-law fit, fit_sublimation_laws.py)"
            law["compare"] = species
        law["max_error"] = max_relative_error(law["T0"], law["rho0"], law["gamma"], law["compare"])
        out[name] = law
    return out


def sub_file_content(dat_file, name, law, rho_ref, rho_min, rho_max):
    T_ref = power_law(rho_ref, law["T0"], law["rho0"], law["gamma"])
    fitted = "fit" in laws[name]
    lines = [
        f"# Sublimation properties for {dat_file} ({name})",
        "# Generated by fit_sublimation_laws.py (MCFOST src directory)",
        "# T_sub = T0 (rho_gas / rho0)^gamma, rho_gas: total gas density [g/cm3]",
    ]
    if fitted:
        lines.append(f"# Least-squares fit of log T vs log rho to {P94_ref} ({law['compare']}),")
        lines.append(f"# gas densities {rho_min:.0e} to {rho_max:.0e} g/cm3")
    lines += [
        f"# Maximum deviation from {P94_ref} ({law['compare']}, 1e-18 to 1e-4 g/cm3): "
        f"{100 * law['max_error']:.1f}%",
        f"# T_sub({rho_ref:.0e} g/cm3) = {T_ref:.0f} K (constant value in {dat_file})",
        "format_version = 1",
        "law = power_law",
        f"T0 = {law['T0']:.1f}                      # K",
        f"rho0 = {law['rho0']:.1f}                       # g cm^-3",
        f"gamma = {law['gamma']:.5f}",
        f"reference = {law['reference']}",
    ]
    return "\n".join(lines) + "\n"


def set_dat_T_sub(text, T_sub):
    """Replaces the sublimation temperature (2nd value of the first non-comment line)."""
    lines = text.split("\n")
    i = next(k for k, l in enumerate(lines) if not l.lstrip().startswith("#"))
    line = lines[i]
    tokens = line.split()
    old = tokens[1]
    if "." not in old:
        new = f"{T_sub:.0f}"
    elif old.endswith("."):
        new = f"{T_sub:.0f}."
    else:
        new = f"{T_sub:.{len(old.split('.')[1])}f}"
    # replace the second token in place, keeping the spacing
    start = line.index(tokens[0]) + len(tokens[0])
    start = line.index(old, start)
    lines[i] = line[:start] + new + line[start + len(old):]
    return "\n".join(lines), old, new


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output_dir", help="write the .sub and updated .dat files in this directory")
    parser.add_argument("--dust_dir", default=os.path.join(os.environ.get("MCFOST_UTILS", ""), "Dust"),
                        help="directory of the optical indices files (default: $MCFOST_UTILS/Dust)")
    parser.add_argument("--rho_ref", type=float, default=1e-10,
                        help="gas density [g/cm3] of the constant T_sub written in the .dat files (default: 1e-10)")
    parser.add_argument("--rho_min", type=float, default=1e-18, help="fit range [g/cm3] (default: 1e-18)")
    parser.add_argument("--rho_max", type=float, default=1e-4, help="fit range [g/cm3] (default: 1e-4)")
    args = parser.parse_args()

    fitted = get_laws(args.rho_min, args.rho_max)

    print(f"{'law':10s} {'T0 [K]':>8s} {'rho0':>6s} {'gamma':>8s} {'T(rho_ref) [K]':>14s} {'max dev.':>8s}  source")
    for name, law in fitted.items():
        T_ref = power_law(args.rho_ref, law["T0"], law["rho0"], law["gamma"])
        print(f"{name:10s} {law['T0']:8.1f} {law['rho0']:6.1f} {law['gamma']:8.5f} {T_ref:14.0f} "
              f"{100 * law['max_error']:7.1f}%  {law['reference']}")

    if args.output_dir is None:
        return

    os.makedirs(args.output_dir, exist_ok=True)
    for dat_file, name in dust_files.items():
        law = fitted[name]
        base = os.path.splitext(dat_file)[0]
        with open(os.path.join(args.output_dir, base + ".sub"), "w") as f:
            f.write(sub_file_content(dat_file, name, law, args.rho_ref, args.rho_min, args.rho_max))

        src = os.path.join(args.dust_dir, dat_file)
        if not os.path.isfile(src):
            print(f"{dat_file}: not found in {args.dust_dir}, .dat not updated")
            continue
        with open(src) as f:
            text = f.read()
        T_ref = power_law(args.rho_ref, law["T0"], law["rho0"], law["gamma"])
        text, old, new = set_dat_T_sub(text, T_ref)
        with open(os.path.join(args.output_dir, dat_file), "w") as f:
            f.write(text)
        print(f"{dat_file:24s} {name:10s} T_sub {old:>7s} -> {new}")


if __name__ == "__main__":
    main()
